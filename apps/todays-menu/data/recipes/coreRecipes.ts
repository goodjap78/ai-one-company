import type { CoreRecipe, CoreNutrition } from '../../types/coreRecipe';
import type { RecipeIngredient } from '../../types/recipe';

type StepDraft = { guide: string; instruction: string };

type RecipeDraft = Omit<CoreRecipe, 'cookingSteps' | 'calories' | 'nutrition'> & {
  cookingSteps: StepDraft[];
  nutrition: CoreNutrition;
};

function defineRecipe(draft: RecipeDraft): CoreRecipe {
  return {
    ...draft,
    calories: draft.nutrition.calories,
    cookingSteps: draft.cookingSteps.map((step, index) => ({
      order: index + 1,
      guide: step.guide,
      instruction: step.instruction,
    })),
  };
}

function ing(name: string, amount: string, optional?: boolean): RecipeIngredient {
  return optional ? { name, amount, optional } : { name, amount };
}

function nut(calories: number, protein: number, carbs: number, fat: number): CoreNutrition {
  return { calories, protein, carbs, fat };
}

